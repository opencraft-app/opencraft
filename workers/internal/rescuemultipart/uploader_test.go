package rescuemultipart

import (
	"bytes"
	"context"
	"errors"
	"io"
	"reflect"
	"strings"
	"testing"
)

type fakeClient struct {
	attempts      []int
	parts         [][]byte
	completed     []CompletedPart
	failPartOnce  int
	failedPartHit bool
	completeErr   error
}

func (f *fakeClient) UploadPart(_ context.Context, number int, data []byte) (string, error) {
	f.attempts = append(f.attempts, number)
	if number == f.failPartOnce && !f.failedPartHit {
		f.failedPartHit = true
		return "", errors.New("temporary upload failure")
	}
	f.parts = append(f.parts, append([]byte(nil), data...))
	return "etag", nil
}

func (f *fakeClient) Complete(_ context.Context, parts []CompletedPart) error {
	f.completed = append([]CompletedPart(nil), parts...)
	return f.completeErr
}

func TestUploadReturnsCompleteFailure(t *testing.T) {
	client := &fakeClient{completeErr: errors.New("complete failed")}
	result, err := Upload(context.Background(), client, func(out io.Writer) error {
		_, err := out.Write([]byte("archive"))
		return err
	}, Options{PartSize: 4, MaxParts: 10, MaxAttempts: 1})
	if err == nil || !strings.Contains(err.Error(), "complete multipart upload") {
		t.Fatalf("error = %v", err)
	}
	var uploadErr *UploadError
	if !errors.As(err, &uploadErr) || uploadErr.Stage != StageComplete || uploadErr.PartNumber != 0 {
		t.Fatalf("typed error = %#v", uploadErr)
	}
	if result.UploadedBytes != 7 || result.PartCount != 2 {
		t.Fatalf("result = %+v", result)
	}
}

func TestUploadSplitsUnknownLengthStreamAndCompletesInOrder(t *testing.T) {
	client := &fakeClient{}
	result, err := Upload(context.Background(), client, func(out io.Writer) error {
		_, err := io.Copy(out, bytes.NewReader([]byte("abcdefghij")))
		return err
	}, Options{PartSize: 4, MaxParts: 10, MaxAttempts: 1})
	if err != nil {
		t.Fatal(err)
	}
	if got := client.parts; !reflect.DeepEqual(got, [][]byte{[]byte("abcd"), []byte("efgh"), []byte("ij")}) {
		t.Fatalf("parts = %q", got)
	}
	if got := client.completed; !reflect.DeepEqual(got, []CompletedPart{{Number: 1, ETag: "etag"}, {Number: 2, ETag: "etag"}, {Number: 3, ETag: "etag"}}) {
		t.Fatalf("completed = %#v", got)
	}
	if result.Bytes != 10 || result.UploadedBytes != 10 || result.PartCount != 3 || len(result.SHA256) != 64 {
		t.Fatalf("result = %+v", result)
	}
}

func TestUploadReportsGeneratedAndUploadedBytesOnFailure(t *testing.T) {
	client := &fakeClient{failPartOnce: 2}
	result, err := Upload(context.Background(), client, func(out io.Writer) error {
		_, err := out.Write([]byte("abcdefghij"))
		return err
	}, Options{PartSize: 4, MaxParts: 10, MaxAttempts: 1})
	if err == nil {
		t.Fatal("expected upload failure")
	}
	var uploadErr *UploadError
	if !errors.As(err, &uploadErr) || uploadErr.Stage != StageUploadPart || uploadErr.PartNumber != 2 {
		t.Fatalf("typed error = %#v", uploadErr)
	}
	if result.UploadedBytes != 4 {
		t.Fatalf("uploaded bytes = %d, want 4", result.UploadedBytes)
	}
	if result.Bytes < result.UploadedBytes {
		t.Fatalf("generated bytes = %d, uploaded bytes = %d", result.Bytes, result.UploadedBytes)
	}
}

func TestUploadRetriesTheSamePartNumber(t *testing.T) {
	client := &fakeClient{failPartOnce: 2}
	_, err := Upload(context.Background(), client, func(out io.Writer) error {
		_, err := out.Write([]byte("abcdefghij"))
		return err
	}, Options{
		PartSize:    4,
		MaxParts:    10,
		MaxAttempts: 2,
		Sleep:       func(context.Context, int) error { return nil },
	})
	if err != nil {
		t.Fatal(err)
	}
	if got := client.attempts; !reflect.DeepEqual(got, []int{1, 2, 2, 3}) {
		t.Fatalf("attempts = %v", got)
	}
}

func TestUploadDoesNotCompleteAfterArchiveFailure(t *testing.T) {
	client := &fakeClient{}
	wantErr := errors.New("archive failed")
	_, err := Upload(context.Background(), client, func(out io.Writer) error {
		_, _ = out.Write([]byte("abcde"))
		return wantErr
	}, Options{PartSize: 4, MaxParts: 10, MaxAttempts: 1})
	if !errors.Is(err, wantErr) {
		t.Fatalf("error = %v, want %v", err, wantErr)
	}
	if len(client.completed) != 0 {
		t.Fatalf("Complete called after archive failure: %#v", client.completed)
	}
}

func TestUploadRejectsMoreThanMaxParts(t *testing.T) {
	client := &fakeClient{}
	_, err := Upload(context.Background(), client, func(out io.Writer) error {
		_, err := out.Write([]byte("abcdefghij"))
		return err
	}, Options{PartSize: 4, MaxParts: 2, MaxAttempts: 1})
	if !errors.Is(err, ErrTooManyParts) {
		t.Fatalf("error = %v, want ErrTooManyParts", err)
	}
	if len(client.completed) != 0 {
		t.Fatalf("Complete called after part limit: %#v", client.completed)
	}
}
