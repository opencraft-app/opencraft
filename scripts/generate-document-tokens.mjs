import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const source = await readFile(new URL('packages/design-system/src/tokens.web.scss', root), 'utf8');
const palette = Object.fromEntries([...source.matchAll(/(--gray-\d+):\s*([^;]+);/g)].map(([, key, value]) => [key, value]));
const result = '// Generated by scripts/generate-document-tokens.mjs from tokens.web.scss.\n'
  + 'export const documentBaseTokens = ' + JSON.stringify(palette, null, 2) + ' as const;\n';
const target = new URL('packages/design-system/src/document-tokens.generated.ts', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== result) throw new Error('Standalone document tokens drifted; run node scripts/generate-document-tokens.mjs');
} else await writeFile(target, result);
