import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { readOwnerMigrations, assertOwnerCoverage } from './storage-owner-source.mjs';
import { digest, compileStore, freezeStore, assertSchemaCurrent } from './storage-migration-tools.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const stores = JSON.parse(readFileSync(join(root, 'packages/storage-node/stores.json'), 'utf8'));
const command = process.argv[2] ?? 'check';
if (!['check', 'compile', 'generate', 'freeze'].includes(command)) throw new Error('Use check, compile, generate or freeze');
const selected = process.argv.includes('--store') ? process.argv[process.argv.indexOf('--store') + 1] : 'server';
if (selected !== 'server' && !stores.some(store => store.id === selected)) throw new Error('Unknown storage owner');
const serverCompiler = flags => execFileSync(process.execPath, [join(root, 'scripts/compile-storage-migrations.mjs'), ...flags], { cwd: root, stdio: 'inherit' });
if (command === 'generate') {
  // Reject an edited published chain before Drizzle can derive another snapshot.
  if (selected === 'server') serverCompiler([]);
  else compileStore(join(root, 'packages/storage-node/src/stores', selected));
  const config = selected === 'server' ? 'packages/storage-node/drizzle.config.ts' : `packages/storage-node/src/stores/${selected}/drizzle.config.ts`;
  // The Server config predates the multi-owner entry and uses package-local paths.
  execFileSync(process.execPath, [join(root, 'node_modules/drizzle-kit/bin.cjs'), 'generate', '--config=' + (selected === 'server' ? 'drizzle.config.ts' : config)],
    { cwd: selected === 'server' ? join(root, 'packages/storage-node') : root, stdio: 'inherit' });
}
serverCompiler(command === 'check' ? ['--check'] : command === 'freeze' && selected === 'server' ? ['--freeze'] : []);
if (command === 'freeze' && selected !== 'server') freezeStore(join(root, 'packages/storage-node/src/stores', selected));
const result = Object.fromEntries(stores.map(store => [store.id, compileStore(join(root, 'packages/storage-node/src/stores', store.id), { requirePublished: command === 'check' })]));
const output = join(root, 'packages/sqlite-node/src/store-migrations.generated.ts');
const content = '// Generated by storage-migrations.mjs; do not edit.\nexport const STORE_MIGRATIONS = ' + JSON.stringify(result, null, 2) + ' as const;\n';
if (command === 'check') {
  assertOwnerCoverage(root, stores);
  if (readFileSync(output, 'utf8') !== content) throw new Error('Storage SQL and bundled owner migrations differ');
  for (const store of [{ id: 'server' }, ...stores]) {
    if (store.id !== 'server') {
      const legacy = await readOwnerMigrations(root, store);
      const identities = legacy.map(({ version, name, sql }) => ({ version, name, checksum: digest(sql) }));
      if (JSON.stringify(identities) !== JSON.stringify(result[store.id].baseline)) throw new Error(`Published owner history changed: ${store.id}`);
    }
    await assertSchemaCurrent(join(root, 'packages/storage-node/src', store.id === 'server' ? 'server' : 'stores/' + store.id));
  }
} else writeFileSync(output, content);
console.log(`Storage schemas: server + ${stores.length} independent owners`);
