import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const registryPath = resolve(root, "packages/design-system/src/typography/typography.tokens.json");
const outputPath = resolve(root, "packages/design-system/src/typography/_generated.web.scss");
const rolesPath = resolve(root, "packages/design-system/src/typography/_roles.web.scss");
const registry = JSON.parse(await readFile(registryPath, "utf8"));
const kebab = (value) => value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
const weight = (name) => registry.weights[name];
const roles = registry.platforms.web.roles;
const scales = registry.platforms.web.scales;

const lines = [
  "// DO NOT EDIT. Generated by scripts/generate-typography.mjs.",
  '@forward "./roles.web";',
  "",
  ":root {",
  ...Object.entries(registry.families).map(([name, definition]) => `  --font-family-${kebab(name)}: ${definition.web};`),
  "  --font-sans: var(--font-family-ui);",
  "  --font-mono: var(--font-family-mono);",
  ...Object.entries(registry.weights).map(([name, value]) => `  --font-weight-${name}: ${value};`),
  ...Object.entries(registry.tracking).map(([name, value]) => `  --font-tracking-${name}: ${value}em;`),
];

for (const [name, definition] of Object.entries(roles)) {
  const roleName = kebab(name);
  const scale = scales[definition.scale];
  lines.push(
    `  --typography-${roleName}-family: var(--font-family-${definition.family});`,
    `  --typography-${roleName}-size: ${scale.fontSize}px;`,
    `  --typography-${roleName}-line-height: ${scale.lineHeight}px;`,
    `  --typography-${roleName}-weight: ${weight(definition.weight)};`,
    `  --typography-${roleName}-leading: ${scale.lineHeight - scale.fontSize}px;`,
    `  --typography-${roleName}-tracking: var(--font-tracking-normal);`,
    `  --typography-${roleName}-font: var(--typography-${roleName}-weight) var(--typography-${roleName}-size)/var(--typography-${roleName}-line-height) var(--typography-${roleName}-family);`,
  );
}

lines.push(
  `  --font-text-lg-size: ${scales.textLg.fontSize}px;`,
  `  --font-text-lg-line-height: ${scales.textLg.lineHeight}px;`,
  `  --font-text-md-size: ${scales.textMd.fontSize}px;`,
  `  --font-text-md-line-height: ${scales.textMd.lineHeight}px;`,
  "  --font-text-sm-size: var(--typography-body-size);",
  "  --font-text-sm-line-height: var(--typography-body-line-height);",
  `  --font-text-xs-size: ${scales.textXs.fontSize}px;`,
  `  --font-text-xs-line-height: ${scales.textXs.lineHeight}px;`,
  `  --font-text-2xs-size: ${scales.text2xs.fontSize}px;`,
  `  --font-text-2xs-line-height: ${scales.text2xs.lineHeight}px;`,
  "  --opencraft-sidebar-font-size: var(--typography-navigation-action-size);",
  "  --opencraft-sidebar-line-height: var(--typography-navigation-action-line-height);",
  "  --opencraft-sidebar-meta-font-size: var(--typography-metadata-size);",
  "  --opencraft-sidebar-meta-line-height: var(--typography-metadata-line-height);",
  "}",
  "",
);

const outputs = new Map([
  [outputPath, `${lines.join("\n")}\n`],
  [rolesPath, `// DO NOT EDIT. Generated by scripts/generate-typography.mjs.\n$typography-role-names: (${Object.keys(roles).map(kebab).join(", ")});\n`],
]);
for (const [path, generated] of outputs) {
  if (process.argv.includes("--check")) {
    const existing = await readFile(path, "utf8").catch(() => "");
    if (existing !== generated) {
      console.error("Typography Web adapter is stale. Run npm run generate:typography.");
      process.exitCode = 1;
    }
  } else {
    await writeFile(path, generated);
    console.log(`Generated ${path}`);
  }
}
