#!/usr/bin/env bash

set -euo pipefail

require_deploy_env_name() {
  local env_name="${1:-${ENV:-}}"
  if [[ -z "${env_name}" ]]; then
    echo "ERROR: ENV is required. Example: ENV=shprod bash <service>/scripts/deploy-k8s.sh" >&2
    return 1
  fi
  printf '%s\n' "${env_name}"
}

load_deploy_env() {
  local mono_dir="$1"
  local env_name="${2:-}"
  local env_dir="${mono_dir}/deploy/envs/${env_name}"
  local platform_env="${env_dir}/platform.env"
  local resolved_kubeconfig=""

  if [[ -z "${env_name}" ]]; then
    echo "ERROR: deploy environment name is required" >&2
    return 1
  fi

  if [[ ! -f "${platform_env}" ]]; then
    echo "ERROR: missing deploy environment file: ${platform_env}" >&2
    return 1
  fi

  export DEPLOY_ENV_NAME="${env_name}"
  export DEPLOY_ENV_DIR="${env_dir}"

  while IFS= read -r line || [[ -n "${line}" ]]; do
    [[ -z "${line}" || "${line}" =~ ^[[:space:]]*# ]] && continue
    if [[ "${line}" != *"="* ]]; then
      echo "ERROR: invalid env line in ${platform_env}: ${line}" >&2
      return 1
    fi
    local key="${line%%=*}"
    local value="${line#*=}"
    export "${key}=${value}"
  done < "${platform_env}"

  if [[ -n "${DEPLOY_KUBECONFIG:-}" ]]; then
    resolved_kubeconfig="$(resolve_deploy_env_path "${mono_dir}" "${DEPLOY_KUBECONFIG}")"
    if [[ ! -f "${resolved_kubeconfig}" ]]; then
      echo "ERROR: missing deploy kubeconfig file: ${resolved_kubeconfig}" >&2
      return 1
    fi

    # Default to the kubeconfig generated by infractl sync/up so deploy scripts
    # don't accidentally hit a stale shell-level KUBECONFIG from another cluster.
    if [[ "${DEPLOY_RESPECT_EXISTING_KUBECONFIG:-0}" != "1" || -z "${KUBECONFIG:-}" ]]; then
      export KUBECONFIG="${resolved_kubeconfig}"
    fi
  fi
}

resolve_deploy_env_path() {
  local mono_dir="$1"
  local path_value="$2"

  if [[ "${path_value}" = /* ]]; then
    printf '%s\n' "${path_value}"
  else
    printf '%s\n' "${mono_dir}/${path_value}"
  fi
}
