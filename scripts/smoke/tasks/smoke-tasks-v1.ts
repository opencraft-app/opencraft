import assert from "node:assert/strict";
import { mkdtemp, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { tmpdir } from "node:os";
import WebSocket from "ws";
import { startHeadlessServer } from "../../headless-server.mjs";
const { expect } = await import("@playwright/test");
const { chromium } = await import(process.env.OPENCRAFT_PLAYWRIGHT_MODULE ?? "playwright");
const root = process.cwd(), dataDirectory = await mkdtemp(join(tmpdir(), "tasks-v1-workbench-"));
const artifacts = process.env.OPENCRAFT_TASKS_V1_ARTIFACTS ?? await mkdtemp(join(tmpdir(), "tasks-v1-artifacts-"));
const server = await startHeadlessServer({ root, dataDirectory, port: 0, webRoot: join(root, "apps/workbench-web/dist"), dshCapabilityPlugin: join(root, "apps/local-agent-host/src/dsh-capability-plugin.mjs"), codexExecutable: process.env.OPENCRAFT_CODEX_EXECUTABLE ?? "codex" });
const socket = new WebSocket(server.url.replace(/^http/, "ws") + "/appserver", { origin: server.url });
let browser: any;
const errors: string[] = [];
try {
  await new Promise<void>((resolve, reject) => { socket.once("open", resolve); socket.once("error", reject); });
  let seq = 0;
  const rpc = (method: string, params: unknown = {}): Promise<any> => new Promise((resolve, reject) => {
    const id = ++seq, timer = setTimeout(() => { socket.off("message", receive); reject(new Error(`Timed out: ${method}`)); }, 15000);
    const receive = (raw: WebSocket.RawData) => { const frame = JSON.parse(String(raw)); if (frame.id !== id) return; clearTimeout(timer); socket.off("message", receive); frame.error ? reject(new Error(`RPC ${method} (${frame.error.code})`)) : resolve(frame.result); };
    socket.on("message", receive); socket.send(JSON.stringify({ jsonrpc: "2.0", id, method, params }));
  });
  await rpc("initialize", { clientInfo: { name: "tasks-v1-smoke", version: "1" } });
  const content = { description: "Original description", projectId: null, projectServerId: null, acceptanceCriteria: "Verify the complete workflow" };
  await rpc("opencraft/tasks/create", { ...content, id: "harness", title: "Harness baseline", kind: "harness", status: "backlog" });
  await rpc("opencraft/tasks/create", { ...content, id: "growth", title: "Growth baseline", kind: "growth", status: "todo" });
  browser = await chromium.launch({ headless: true, executablePath: process.env.OPENCRAFT_CHROMIUM_EXECUTABLE, args: ["--no-sandbox", "--disable-dev-shm-usage"] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } }); page.setDefaultTimeout(15000);
  await page.addInitScript(() => localStorage.setItem("opencraft.appearance-theme", "system"));
  page.on("pageerror", (error: Error) => errors.push(error.message));
  await page.goto(server.url + "/views/opencraft.tasks.board");
  await page.locator('[data-task-id="harness"]').waitFor();
  await page.reload();
  await page.locator('[data-task-id="harness"]').waitFor();
  const column = page.locator('.tasks-column[data-status="backlog"]');
  await column.getByRole("button", { name: "Add an item", exact: true }).click();
  const inline = column.getByLabel("Enter a title, then press Enter");
  await inline.fill("Inline new item");
  await inline.dispatchEvent("keydown", { key: "Enter", code: "Enter", keyCode: 229, isComposing: true });
  assert.equal((await rpc("opencraft/tasks/list")).tasks.length, 2, "IME composition must not submit");
  await inline.press("Enter"); await column.getByRole("button", { name: "Inline new item", exact: true }).waitFor();
  await expect(inline).toHaveValue(""); await inline.press("Escape");
  assert.equal((await rpc("opencraft/tasks/list")).tasks.filter((t: any) => t.title === "Inline new item").length, 1);
  await page.locator('[data-task-id="harness"]').hover();
  await page.getByRole("button", { name: "Quick edit: Harness baseline", exact: true }).click();
  const quick = page.locator('.tasks-quick-form'); await quick.getByLabel("Title", { exact: true }).fill("Quick draft retained");
  await quick.getByRole("button", { name: "Open full details", exact: true }).click();
  let dialog = page.locator('.tasks-dialog'); await dialog.waitFor();
  assert.equal(await dialog.getByLabel("Title", { exact: true }).inputValue(), "Quick draft retained");
  await dialog.getByRole("button", { name: "Close task details", exact: true }).click();
  await page.locator('[data-task-id="harness"] .tasks-card__title').click();
  assert.equal(await dialog.getByLabel("Title", { exact: true }).inputValue(), "Quick draft retained");
  await dialog.getByLabel("Type", { exact: true }).selectOption("growth");
  await dialog.getByLabel("Acceptance criteria", { exact: true }).fill("Activation improves with evidence");
  await dialog.getByRole("button", { name: "Save", exact: true }).filter({ visible: true }).click();
  await page.waitForFunction(() => document.querySelector('.tasks-card__title')?.textContent === "Quick draft retained");
  let task = await rpc("opencraft/tasks/read", { id: "harness" }); assert.equal(task.kind, "growth"); assert.equal(task.acceptanceCriteria, "Activation improves with evidence");
  const revision = task.revision;
  await dialog.getByLabel("Title", { exact: true }).fill("Unsaved during progress");
  await dialog.getByLabel("Record progress, a finding or the next step…").fill("Evidence collected; next verify recovery");
  await dialog.getByRole("button", { name: "Post progress", exact: true }).click();
  await dialog.locator('.tasks-activity__text').filter({ hasText: "Evidence collected" }).waitFor();
  task = await rpc("opencraft/tasks/read", { id: "harness" }); assert.equal(task.revision, revision); assert.equal(task.latestProgress.text, "Evidence collected; next verify recovery");
  assert.equal(await dialog.getByLabel("Title", { exact: true }).inputValue(), "Unsaved during progress");
  await page.screenshot({ path: join(artifacts, "detail-desktop.png") });
  await dialog.getByRole("button", { name: "Close task details", exact: true }).click();
  await page.getByLabel("Type", { exact: true }).selectOption("harness"); assert.equal(await page.locator('.tasks-card').count(), 0);
  await page.getByLabel("Type", { exact: true }).selectOption("growth"); assert.equal(await page.locator('.tasks-card').count(), 2);
  await page.getByLabel("Type", { exact: true }).selectOption("");
  await page.screenshot({ path: join(artifacts, "board-desktop.png") });
  await page.getByRole("button", {name:"Hide sidebar",exact:true}).filter({visible:true}).first().click();
  for (const theme of ["light", "dark"]) for (const width of [320, 390, 600, 820]) {
    await page.setViewportSize({ width, height: width === 320 ? 640 : 900 }); await page.emulateMedia({ colorScheme: theme });
    await page.waitForFunction(theme => document.documentElement.dataset.theme === theme, theme);
    await page.waitForFunction(() => (document.querySelector(".tasks-viewport")?.getBoundingClientRect().width ?? 0) >= Math.min(innerWidth - 20, 290));
    if (await page.locator(".tasks-statuses").isVisible()) await page.locator(".tasks-statuses").getByRole("radio", { name: /^Backlog/ }).click();
    await page.locator('[data-task-id="harness"] .tasks-card__title').click();
    dialog = page.locator('.tasks-dialog'); await dialog.waitFor();
    assert.equal(await dialog.getByLabel("Title", { exact: true }).inputValue(), "Unsaved during progress");
    if (width <= 820) {
      await dialog.getByRole("radio", { name: "Activity", exact: true }).click();
      await dialog.getByLabel("Record progress, a finding or the next step…").fill("Retained progress draft");
      await dialog.getByRole("radio", { name: "Content", exact: true }).click();
      assert.equal(await dialog.getByLabel("Title", { exact: true }).inputValue(), "Unsaved during progress");
    }
    const bounds = await dialog.evaluate((el: Element) => { const r = el.getBoundingClientRect(); return { left: r.left, right: r.right, width: innerWidth, scroll: document.documentElement.scrollWidth }; });
    assert.ok(bounds.left >= 0 && bounds.right <= bounds.width + 1 && bounds.scroll <= bounds.width + 1, `No overflow at ${width}/${theme}`);
    if (width === 390) await page.screenshot({ path: join(artifacts, `detail-mobile-${theme}.png`) });
    await dialog.getByRole("button", { name: "Close task details", exact: true }).click();
    if (width === 390) await page.screenshot({ path: join(artifacts, `board-mobile-${theme}.png`) });
  }
  assert.deepEqual(errors, []);
  await writeFile(join(artifacts, "results.json"), JSON.stringify({ passed: true, errors, isolatedData: true, realWorkbenchAndSqlite: true, paidInference: false }, null, 2));
  console.log(`Tasks V1 actual Workbench verification passed: ${artifacts}`);
} finally { socket.terminate(); await browser?.close(); await server.close(); }
