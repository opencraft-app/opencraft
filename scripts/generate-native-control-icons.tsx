import { readFileSync, writeFileSync } from "node:fs";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { CheckboxIcon, IndeterminateCheckboxIcon, DateIcon, NumberStepperIcon, CloseIcon, ChevronDownIcon, ChevronRightIcon } from "../packages/design-system-web/src/action-icons";

// Native pseudo-elements cannot contain React children. Export alpha masks from
// the real artwork so native controls and JSX never acquire separate drawings.
const glyphs = {
  date: <DateIcon />,
  close: <CloseIcon />,
  checkbox: <CheckboxIcon />,
  "checkbox-checked": <CheckboxIcon checked />,
  "checkbox-indeterminate": <IndeterminateCheckboxIcon />,
  "number-stepper": <NumberStepperIcon />,
  "chevron-down": <ChevronDownIcon />,
  "chevron-right": <ChevronRightIcon />,
};
const output = new URL("../packages/design-system-web/src/_native-control-icons.generated.scss", import.meta.url);
const source = `// Generated by scripts/generate-native-control-icons.tsx; edit shared SVG artwork.\n:root {\n${Object.entries(glyphs).map(([name, glyph]) => {
  const svg = renderToStaticMarkup(glyph).replace("<svg ", '<svg xmlns="http://www.w3.org/2000/svg" ').replaceAll("currentColor", "black");
  return `  --ui-control-icon-${name}: url("data:image/svg+xml,${encodeURIComponent(svg)}");`;
}).join("\n")}\n}\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== source) throw new Error("Native control SVG masks are stale; run npm run generate:control-icons");
  console.log("Native control SVG masks match shared artwork.");
} else writeFileSync(output, source);
