import assert from 'node:assert/strict';
import test from 'node:test';
import { reportRecoveryEvent } from '../../apps/workbench-web/src/runtime/recovery-diagnostics';
import { setLocalDiagnosticsEnabled, captureLocalDiagnostics } from '../../apps/workbench-web/src/runtime/local-diagnostics';
test('recovery is opt-in, local only, and retains its metadata allowlist', context => {
 let uploads=0;
 context.mock.method(globalThis,'fetch',async()=>{uploads++;return new Response('{}');});
 setLocalDiagnosticsEnabled(false);
 reportRecoveryEvent({recoveryId:'disabled',stage:'history-started'});
 setLocalDiagnosticsEnabled(true);
 reportRecoveryEvent({recoveryId:'recovery-test-1',stage:'history-started',elapsedMs:0,eventAtMs:123,hostId:'private-id',params:'private-body'});
 reportRecoveryEvent({recoveryId:'recovery-test-1',stage:'settled',elapsedMs:10,eventAtMs:133});
 const samples=captureLocalDiagnostics().samples.filter(x=>x.kind==='recovery');
 assert.deepEqual(samples.map(x=>x.fields.stage),['history-started','settled']);
 assert.doesNotMatch(JSON.stringify(samples),/private-id|private-body|disabled/);
 assert.equal(uploads,0);
 setLocalDiagnosticsEnabled(false);
 reportRecoveryEvent({recoveryId:'disabled-again',stage:'settled'});
 assert.equal(captureLocalDiagnostics().samples.filter(x=>x.kind==='recovery').length,2);
});
