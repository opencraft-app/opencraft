#!/usr/bin/env bash

set -euo pipefail

REGION="${HERMES_TAT_REGION:-ap-shanghai}"
SCRIPT_FILE="${HERMES_TAT_SCRIPT_FILE:-images/helpers/config-hermes-python-mirrors.sh}"
BLUEPRINT_ID_FILE="${HERMES_BACKEND_BLUEPRINT_ID_FILE:-images/hermes-backend-blueprint-id}"
OUTPUT_ENV_FILE="${HERMES_TAT_COMMAND_ENV_FILE:-}"
COMMAND_NAME_PREFIX="${HERMES_TAT_COMMAND_NAME_PREFIX:-hermes-existing-vm-upgrade}"
COMMAND_TIMEOUT="${HERMES_TAT_COMMAND_TIMEOUT:-600}"
COMMAND_USER="${HERMES_TAT_COMMAND_USER:-root}"
COMMAND_WORKDIR="${HERMES_TAT_COMMAND_WORKDIR:-/tmp}"

usage() {
  cat <<'EOF'
Usage:
  HERMES_TAT_REGION=ap-shanghai \
  HERMES_TAT_SCRIPT_FILE=images/helpers/config-hermes-python-mirrors.sh \
    bash .ci/runtime/commands/create_hermes_tat_command.sh

Create a Tencent Cloud TAT command from a checked-in Hermes repair script.

Environment:
  HERMES_TAT_REGION
      Default: ap-shanghai.
  HERMES_TAT_SCRIPT_FILE
      Default: images/helpers/config-hermes-python-mirrors.sh.
  HERMES_BACKEND_BLUEPRINT_ID_FILE
      File containing the Hermes backend blueprint id. Default: images/hermes-backend-blueprint-id.
  HERMES_TAT_COMMAND_ENV_FILE
      Optional path to write shell exports for the created command.
  HERMES_TAT_COMMAND_NAME_PREFIX
      Default: hermes-existing-vm-upgrade.
  HERMES_TAT_COMMAND_TIMEOUT
      Default: 600.
  HERMES_TAT_COMMAND_USER
      Default: root.
  HERMES_TAT_COMMAND_WORKDIR
      Default: /tmp.
EOF
}

log() {
  printf '[create-hermes-tat-command] %s\n' "$*" >&2
}

fail() {
  printf '[create-hermes-tat-command] ERROR: %s\n' "$*" >&2
  exit 1
}

require_cmd() {
  command -v "$1" >/dev/null 2>&1 || fail "missing required command: $1"
}

[[ "${1:-}" != "-h" && "${1:-}" != "--help" ]] || {
  usage
  exit 0
}

[[ -r "$SCRIPT_FILE" ]] || fail "script file is not readable: $SCRIPT_FILE"
[[ -r "$BLUEPRINT_ID_FILE" ]] || fail "Hermes backend blueprint id file is not readable: $BLUEPRINT_ID_FILE"
[[ "$COMMAND_TIMEOUT" =~ ^[0-9]+$ && "$COMMAND_TIMEOUT" -gt 0 ]] || fail "HERMES_TAT_COMMAND_TIMEOUT must be a positive integer"

require_cmd base64
require_cmd date
require_cmd python3
require_cmd tccli

bash -n "$SCRIPT_FILE"
blueprint_id="$(tr -d '[:space:]' < "$BLUEPRINT_ID_FILE")"
[[ "$blueprint_id" =~ ^lhbp-[A-Za-z0-9_-]+$ ]] || fail "invalid Hermes backend blueprint id: ${blueprint_id:-<empty>}"
printf -v blueprint_id_quoted '%q' "$blueprint_id"

stamp="$(date +%Y%m%d%H%M%S)"
command_name="${COMMAND_NAME_PREFIX}-${REGION}-${stamp}"
content_b64="$(
  {
    printf '#!/usr/bin/env bash\n'
    printf 'export HERMES_BACKEND_BLUEPRINT_ID=%s\n' "$blueprint_id_quoted"
    sed '1{/^#!/d;}' "$SCRIPT_FILE"
  } | base64 | tr -d '\n'
)"

log "creating TAT command region=${REGION} name=${command_name} script=${SCRIPT_FILE} blueprint=${blueprint_id}"
response="$(
  tccli tat CreateCommand \
    --region "$REGION" \
    --CommandName "$command_name" \
    --Description "Hermes existing VM repair generated by CI from ${SCRIPT_FILE}" \
    --Content "$content_b64" \
    --CommandType SHELL \
    --Username "$COMMAND_USER" \
    --WorkingDirectory "$COMMAND_WORKDIR" \
    --Timeout "$COMMAND_TIMEOUT"
)"

command_id="$(printf '%s' "$response" | python3 -c 'import json,sys; print(json.load(sys.stdin).get("CommandId", ""))')"
[[ -n "$command_id" ]] || fail "CreateCommand response missing CommandId: $response"

printf 'HERMES_TAT_COMMAND_ID=%s\n' "$command_id"
if [[ -n "$OUTPUT_ENV_FILE" ]]; then
  mkdir -p "$(dirname "$OUTPUT_ENV_FILE")"
  printf 'HERMES_TAT_COMMAND_ID=%q\n' "$command_id" >"$OUTPUT_ENV_FILE"
fi
