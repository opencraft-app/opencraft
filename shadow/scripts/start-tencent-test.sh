#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT_DIR"

export SHADOW_SECRET_ID="${SHADOW_SECRET_ID:-CHANGE_ME_SECRET_ID}"
export SHADOW_SECRET_KEY="${SHADOW_SECRET_KEY:-CHANGE_ME_SECRET_KEY}"
export SHADOW_PLATFORM="${SHADOW_PLATFORM:-lightclaw}"

export SHADOW_PROVIDER="${SHADOW_PROVIDER:-tencent}"
export SHADOW_STORAGE_DRIVER="${SHADOW_STORAGE_DRIVER:-sqlite}"
export SHADOW_STORAGE_DSN="${SHADOW_STORAGE_DSN:-file:shadow.db?_pragma=busy_timeout(5000)}"
export SHADOW_REGION="${SHADOW_REGION:-ap-guangzhou}"
export SHADOW_ACCOUNT_ENDPOINT="${SHADOW_ACCOUNT_ENDPOINT:-account.test.tencentcloudapi.com}"
export SHADOW_CAM_ENDPOINT="${SHADOW_CAM_ENDPOINT:-cam.test.tencentcloudapi.com}"
export SHADOW_STS_ENDPOINT="${SHADOW_STS_ENDPOINT:-sts.test.tencentcloudapi.com}"
if [[ -n "${SHADOW_BILLING_ENDPOINT:-}" && -n "${SHADOW_DIANSHI_ENDPOINT:-}" ]]; then
  export SHADOW_BILLING_MODE="${SHADOW_BILLING_MODE:-http}"
else
  export SHADOW_BILLING_MODE="${SHADOW_BILLING_MODE:-fake}"
fi
if [[ "${SHADOW_BILLING_MODE}" == "http" ]]; then
  export SHADOW_BILLING_ENDPOINT="${SHADOW_BILLING_ENDPOINT:?SHADOW_BILLING_ENDPOINT is required when SHADOW_BILLING_MODE=http}"
  export SHADOW_DIANSHI_ENDPOINT="${SHADOW_DIANSHI_ENDPOINT:?SHADOW_DIANSHI_ENDPOINT is required when SHADOW_BILLING_MODE=http}"
else
  export SHADOW_BILLING_ENDPOINT="${SHADOW_BILLING_ENDPOINT:-}"
  export SHADOW_DIANSHI_ENDPOINT="${SHADOW_DIANSHI_ENDPOINT:-}"
fi
export SHADOW_BILLING_RECOVERY_ENDPOINT="${SHADOW_BILLING_RECOVERY_ENDPOINT:-}"
export SHADOW_FREE_TRIAL_ACTIVITY_ID="${SHADOW_FREE_TRIAL_ACTIVITY_ID:-15152}"
export SHADOW_FREE_TRIAL_ACT_ID="${SHADOW_FREE_TRIAL_ACT_ID:-134393}"
export SHADOW_FREE_TRIAL_SUB_PRODUCT_CODE="${SHADOW_FREE_TRIAL_SUB_PRODUCT_CODE:-sp_tced_saas}"

BIN_DIR="${SHADOW_BIN_DIR:-$ROOT_DIR/bin}"
BIN_PATH="${SHADOW_BIN_PATH:-$BIN_DIR/shadowd}"

make build

exec "$BIN_PATH"
