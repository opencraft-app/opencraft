import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const frontendDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repositoryDir = path.resolve(frontendDir, "..");
const outputPath = path.join(
  frontendDir,
  "src/lib/generated/deepseek-harness-runtime-assets.ts",
);
const checkOnly = process.argv.includes("--check");
const commandChunkSize = 24_000;
const sourceFragmentSize = 120;

const split = (value, size) => {
  const chunks = [];
  for (let offset = 0; offset < value.length; offset += size) {
    chunks.push(value.slice(offset, offset + size));
  }
  return chunks;
};

const formatJoinedString = (value, indent) => {
  const fragments = split(value, sourceFragmentSize)
    .map((fragment) => `${indent}  ${JSON.stringify(fragment)},`)
    .join("\n");
  return `${indent}[\n${fragments}\n${indent}].join("")`;
};

const installerPath = path.join(repositoryDir, "images/helpers/install-deepseek-harness.sh");
const providerHelperPath = path.join(
  repositoryDir,
  "images/helpers/configure-deepseek-harness.py",
);
const sourceFiles = [
  { source: installerPath, target: "installer/install-deepseek-harness.sh", mode: 0o755 },
];

const files = await Promise.all(sourceFiles.map(async ({ source, target, mode }) => ({
  path: target,
  mode,
  content: (await readFile(source)).toString("base64"),
})));
const payload = Buffer.from(JSON.stringify({ schemaVersion: 1, files }), "utf8");
const compressedPayload = gzipSync(payload, { level: 9 });
const payloadBase64 = compressedPayload.toString("base64");
const payloadChunks = split(payloadBase64, commandChunkSize);
const payloadSha256 = createHash("sha256").update(compressedPayload).digest("hex");
const providerHelperBase64 = (await readFile(providerHelperPath)).toString("base64");

const generatedSource = [
  "// Generated by scripts/generate-deepseek-harness-runtime-assets.mjs. Do not edit.",
  "",
  "export const DEEPSEEK_HARNESS_INSTALL_PAYLOAD_CHUNKS = [",
  ...payloadChunks.map((chunk) => `${formatJoinedString(chunk, "  ")},`),
  "] as const;",
  "",
  `export const DEEPSEEK_HARNESS_INSTALL_PAYLOAD_SHA256 = ${JSON.stringify(payloadSha256)};`,
  "",
  `export const DEEPSEEK_HARNESS_PROVIDER_HELPER_BASE64 = ${formatJoinedString(providerHelperBase64, "")};`,
  "",
].join("\n");

if (checkOnly) {
  let current = "";
  try {
    current = await readFile(outputPath, "utf8");
  } catch {
    // A missing generated file is reported as drift below.
  }
  if (current !== generatedSource) {
    console.error("DeepSeek Harness generated runtime payload is out of date");
    process.exitCode = 1;
  }
} else {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, generatedSource, "utf8");
  console.log(
    `Generated ${payloadChunks.length} DeepSeek Harness payload chunks (${payloadBase64.length} base64 bytes)`,
  );
}
