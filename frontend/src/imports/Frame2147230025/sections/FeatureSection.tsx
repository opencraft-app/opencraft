/** 用 scale wrapper 让固定尺寸卡片（464×592）自适应列宽，内部样式不变 */
function CardScaleWrapper({ children }: { children: React.ReactNode }) {
  return (
    <div
      className="relative w-full overflow-hidden rounded-[24px]"
      style={{ paddingBottom: `${(592 / 464) * 100}%` /* aspect-ratio 592:464 */ }}
    >
      <div
        className="absolute top-0 left-0 origin-top-left"
        style={{ width: 464, height: 592, transform: 'scale(var(--card-scale, 1))' }}
        ref={(el) => {
          if (!el) return;
          const parent = el.parentElement;
          if (!parent) return;
          const ro = new ResizeObserver(() => {
            const scale = parent.offsetWidth / 464;
            el.style.setProperty('--card-scale', String(scale));
            el.style.transform = `scale(${scale})`;
          });
          ro.observe(parent);
        }}
      >
        {children}
      </div>
    </div>
  );
}

