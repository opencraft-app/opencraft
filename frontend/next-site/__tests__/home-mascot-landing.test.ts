import { afterEach, expect, it, vi } from 'vitest';
import { mountMascotLanding } from '../home-mascot-landing';
let cleanup: (() => void) | undefined;
afterEach(() => { cleanup?.(); cleanup = undefined; document.body.innerHTML = ''; vi.unstubAllGlobals(); vi.restoreAllMocks(); });
it('plays only the supplied landing clip, freezes its ending and resets on reverse scroll', async () => {
 let notify: IntersectionObserverCallback = () => {};
 const disconnect = vi.fn();
 vi.stubGlobal('IntersectionObserver', class { constructor(cb: IntersectionObserverCallback) { notify = cb; } observe() {} disconnect = disconnect; });
 vi.stubGlobal('matchMedia', () => ({ matches: false, addEventListener() {}, removeEventListener() {} }));
 vi.stubGlobal('innerWidth', 1440);
 const play = vi.spyOn(HTMLMediaElement.prototype, 'play').mockResolvedValue();
 const pause = vi.spyOn(HTMLMediaElement.prototype, 'pause').mockImplementation(() => {});
 vi.spyOn(HTMLMediaElement.prototype, 'load').mockImplementation(() => {});
 document.body.innerHTML = '<main><h2 class="about__head">Features</h2><section class="scenes"></section></main>';
 const root = document.querySelector<HTMLElement>('main')!;
 const landing = mountMascotLanding(root)!; cleanup = landing.stop;
 expect(root.querySelector('.scenes')!.previousElementSibling).toBe(landing.element);
 expect(mountMascotLanding(root)).toBeUndefined();
 const video = landing.element.querySelector('video')!;
 expect(video.src).toContain('mascot-four-landing-v6-refined.webm');
 expect(video.muted).toBe(true); expect(video.loop).toBe(false);
 expect(video.preload).toBe('none');
 expect(landing.ready()).toBe(false);
 Object.defineProperty(video, 'readyState', { configurable: true, value: 2 });
 expect(landing.ready()).toBe(true);
 vi.spyOn(landing.element, 'getBoundingClientRect').mockReturnValue({ top: 400, bottom: 780 } as DOMRect);
 expect(landing.active()).toBe(false);
 landing.land(); expect(landing.active()).toBe(true); expect(play).not.toHaveBeenCalled();
 notify([{ isIntersecting: true } as IntersectionObserverEntry], {} as IntersectionObserver);
 expect(play).toHaveBeenCalledTimes(1);
 video.dispatchEvent(new Event('playing')); expect(landing.element.dataset.state).toBe('playing');
 notify([{ isIntersecting: false } as IntersectionObserverEntry], {} as IntersectionObserver);
 expect(pause).toHaveBeenCalled();
 expect(landing.element.dataset.joined).toBeUndefined();
 video.dispatchEvent(new Event('ended')); expect(landing.element.dataset.state).toBe('still');
 expect(landing.element.querySelectorAll('.home-mascot-landing__arrivals img')).toHaveLength(0);
 landing.reset(); expect(landing.active()).toBe(false); expect(landing.element.dataset.state).toBe('waiting');
 expect(landing.element.dataset.joined).toBeUndefined();
 cleanup(); cleanup = undefined;
 expect(disconnect).toHaveBeenCalledTimes(1); expect(video.hasAttribute('src')).toBe(false);
 expect(root.querySelector('.home-mascot-landing')).toBeNull();
});
it('shows a still without fetching or autoplay when observation is unavailable', () => {
 vi.stubGlobal('IntersectionObserver', undefined);
 vi.stubGlobal('matchMedia', () => ({ matches: false, addEventListener() {}, removeEventListener() {} }));
 vi.spyOn(HTMLMediaElement.prototype, 'pause').mockImplementation(() => {});
 const play = vi.spyOn(HTMLMediaElement.prototype, 'play').mockResolvedValue();
 document.body.innerHTML = '<main><section class="scenes"></section></main>';
 const landing = mountMascotLanding(document.querySelector('main')!)!; cleanup = landing.stop;
 landing.land(); expect(landing.element.dataset.state).toBe('still');
 expect(play).not.toHaveBeenCalled();
});

it('anchors the floor to layout rather than the heading entrance translation', () => {
 vi.stubGlobal('IntersectionObserver', undefined);
 vi.stubGlobal('matchMedia', () => ({ matches: false, addEventListener() {}, removeEventListener() {} }));
 vi.spyOn(HTMLMediaElement.prototype, 'pause').mockImplementation(() => {});
 document.body.innerHTML = '<main><section class="scenes"><h2 class="scenes__title">Use cases</h2></section></main>';
 const root = document.querySelector<HTMLElement>('main')!;
 const title = root.querySelector<HTMLElement>('h2')!;
 vi.spyOn(title, 'offsetTop', 'get').mockReturnValue(350);
 let visualTop = 382;
 vi.spyOn(title, 'getBoundingClientRect').mockImplementation(() => ({ left: 200, top: visualTop } as DOMRect));
 const landing = mountMascotLanding(root)!; cleanup = landing.stop;
 vi.spyOn(landing.element, 'offsetTop', 'get').mockReturnValue(100);
 const media = landing.element.querySelector<HTMLElement>('.home-mascot-landing__media')!;
 vi.spyOn(media, 'getBoundingClientRect').mockReturnValue({ width: 480 } as DOMRect);
 landing.reset();
 expect(media.style.top).toBe('-28px');
 visualTop = 350;
 landing.element.querySelector('video')!.dispatchEvent(new Event('loadeddata'));
 expect(media.style.top).toBe('-28px');
 expect(100 + Number.parseFloat(media.style.top) + 270).toBe(350 - 8);
});
