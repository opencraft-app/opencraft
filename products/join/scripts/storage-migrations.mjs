import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { compileStore, freezeStore, digest, assertSchemaCurrent } from './storage-migration-tools.mjs';
import { readOwnerMigrations, assertOwnerCoverage } from './storage-owner-source.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const coreRoot = resolve(root, '../..');
const stores = JSON.parse(readFileSync(join(root, 'storage/stores.json'), 'utf8'));
const command = process.argv[2] ?? 'check';
if (!['check', 'compile', 'generate', 'freeze'].includes(command)) throw new Error('Use check, compile, generate or freeze');
if (command === 'generate' || command === 'freeze') {
  const id = process.argv[process.argv.indexOf('--store') + 1];
  if (!process.argv.includes('--store') || !stores.some(store => store.id === id)) throw new Error('Select a registered Join store with --store');
  compileStore(join(root, 'storage', id));
  if (command === 'generate') execFileSync(process.execPath, [join(coreRoot, 'node_modules/drizzle-kit/bin.cjs'), 'generate', '--config=' + join(root, 'storage', id, 'drizzle.config.ts')], { cwd: coreRoot, stdio: 'inherit' });
  else freezeStore(join(root, 'storage', id));
}
const result = Object.fromEntries(stores.map(store => [store.id, compileStore(join(root, 'storage', store.id), { requirePublished: command === 'check' })]));
const output = join(root, 'storage/migrations.generated.ts');
const generated = '// Generated by scripts/storage-migrations.mjs; do not edit.\nexport const STORE_MIGRATIONS = ' + JSON.stringify(result, null, 2) + ' as const;\n';
if (command === 'check') {
  assertOwnerCoverage(root, stores, ['plugins']);
  if (readFileSync(output, 'utf8') !== generated) throw new Error('Join storage SQL and bundled migrations differ');
  for (const store of stores) {
    const legacy = await readOwnerMigrations(root, store);
    if (JSON.stringify(legacy.map(({ version, name, sql }) => ({ version, name, checksum: digest(sql) }))) !== JSON.stringify(result[store.id].baseline)) throw new Error('Published Join migration changed');
    await assertSchemaCurrent(join(root, 'storage', store.id));
  }
} else writeFileSync(output, generated);
console.log(`Join private storage schemas: ${stores.length}`);
