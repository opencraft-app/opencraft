#!/usr/bin/env bash
set -euo pipefail

COMPONENT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$COMPONENT_DIR/.." && pwd)"
DOCS_SITE_DIR="${MONO2_DOCS_ROOT:-$ROOT_DIR/docs-site}"
OUT_DIR="$DOCS_SITE_DIR/content/docs/cloudagent"
OUT_FILE="$OUT_DIR/generated-index.mdx"
TMP_FILE="$OUT_FILE.tmp"
OPENAPI_DIR="$DOCS_SITE_DIR/openapi"
OPENAPI_FILE="$OPENAPI_DIR/cloudagent.json"
FRAGMENT_DIR="$DOCS_SITE_DIR/generated/docs-index"
FRAGMENT_FILE="$FRAGMENT_DIR/cloudagent.json"

mkdir -p "$OUT_DIR"
mkdir -p "$OPENAPI_DIR"
mkdir -p "$FRAGMENT_DIR"

{
  printf '%s\n' '---'
  printf '%s\n' 'title: CloudAgent Source Docs Index / CloudAgent 源文档索引'
  printf '%s\n' 'description: Generated index of CloudAgent source documentation files. CloudAgent 源文档文件的生成式索引。'
  printf '%s\n' 'owner: cloudagent'
  printf '%s\n' 'status: active'
  printf '%s\n' 'last_reviewed: "2026-06-16"'
  printf '%s\n' 'tags:'
  printf '%s\n' '  - cloudagent'
  printf '%s\n' '  - generated'
  printf '%s\n' '  - makedocs'
  printf '%s\n' '  - bilingual'
  printf '%s\n' 'source_path: cloudagent/makedocs.sh'
  printf '%s\n' '---'
  printf '\n'
  printf '%s\n' 'This page is generated by `cloudagent/makedocs.sh`.'
  printf '\n'
  printf '%s\n' '本页面由 `cloudagent/makedocs.sh` 生成。'
  printf '\n'
  printf '%s\n' 'It lets CloudAgent own its directory-specific documentation summary while the root docs portal stays generic.'
  printf '\n'
  printf '%s\n' '它让 CloudAgent 自己维护目录级文档摘要，同时保持根文档门户足够通用。'
  printf '\n'
  printf '%s\n' '## Source Files / 源文件'
  printf '\n'
  printf '%s\n' '| Source path | Title / 标题 |'
  printf '%s\n' '| --- | --- |'

  while IFS= read -r file; do
    rel="${file#$ROOT_DIR/}"
    title="$(awk '/^# / { sub(/^# /, ""); print; exit }' "$file")"
    if [ -z "$title" ]; then
      title="$(basename "$file" .md)"
    fi
    printf '| `%s` | %s |\n' "$rel" "$title"
  done < <(find "$COMPONENT_DIR/gateway/docs" -maxdepth 1 -type f -name '*.md' | sort)

  printf '\n'
  printf '%s\n' '## Regeneration / 重新生成'
  printf '\n'
  printf '%s\n' 'Run from repository root:'
  printf '\n'
  printf '%s\n' '从仓库根目录运行：'
  printf '\n'
  printf '%s\n' '```bash'
  printf '%s\n' './makedocs.sh'
  printf '%s\n' '```'
} > "$TMP_FILE"

mv "$TMP_FILE" "$OUT_FILE"
echo "[makedocs] wrote ${OUT_FILE#$ROOT_DIR/}"

TMP_OPENAPI_FILE="$OPENAPI_FILE.tmp"
(
  cd "$COMPONENT_DIR/gateway"
  go run ./cmd/cloudagent-openapi
) > "$TMP_OPENAPI_FILE"
mv "$TMP_OPENAPI_FILE" "$OPENAPI_FILE"

echo "[makedocs] wrote ${OPENAPI_FILE#$ROOT_DIR/}"

cat > "$FRAGMENT_FILE.tmp" <<'JSON'
{
  "object": "mono2.docs.fragment",
  "version": "v1",
  "component": "cloudagent",
  "owner": "cloudagent",
  "source_path": "cloudagent/makedocs.sh",
  "generated": [
    {
      "kind": "mdx",
      "path": "docs-site/content/docs/cloudagent/generated-index.mdx",
      "url": "/docs/cloudagent/generated-index"
    },
    {
      "kind": "openapi",
      "path": "docs-site/openapi/cloudagent.json",
      "url": "/openapi/cloudagent"
    },
    {
      "kind": "api_reference",
      "path": "docs-site/app/reference/cloudagent/route.ts",
      "url": "/reference/cloudagent"
    }
  ]
}
JSON
mv "$FRAGMENT_FILE.tmp" "$FRAGMENT_FILE"
echo "[makedocs] wrote ${FRAGMENT_FILE#$ROOT_DIR/}"
