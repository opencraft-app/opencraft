CREATE TABLE IF NOT EXISTS tasks (
    id                BIGINT AUTO_INCREMENT PRIMARY KEY,
    created_time      DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_time      DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    user_id           VARCHAR(64)  NOT NULL,
    task_id           VARCHAR(64)  NOT NULL,
    parent_task_id    VARCHAR(64)  NOT NULL DEFAULT '',
    task_name         VARCHAR(64)  NOT NULL,
    task_params       JSON         NOT NULL,
    task_state        VARCHAR(16)  NOT NULL DEFAULT 'CREATED',
    task_message      VARCHAR(2048) NOT NULL DEFAULT '',
    trace_id          VARCHAR(64)  NOT NULL DEFAULT '',
    execute_interval  BIGINT       NOT NULL DEFAULT 30,
    execute_count     INT          NOT NULL DEFAULT 0,
    max_execute_count INT          NOT NULL DEFAULT 20,
    last_execute_time DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    UNIQUE KEY uk_task_id (task_id),
    KEY idx_parent_task_id (parent_task_id),
    KEY idx_task_name_state_last_execute (task_name, task_state, last_execute_time),
    KEY idx_user_id (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
