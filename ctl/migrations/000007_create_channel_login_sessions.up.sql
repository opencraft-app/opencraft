CREATE TABLE IF NOT EXISTS channel_login_sessions (
    id                BIGINT AUTO_INCREMENT PRIMARY KEY,
    session_id        VARCHAR(64)   NOT NULL,
    instance_id       VARCHAR(64)   NOT NULL,
    user_id           VARCHAR(64)   NOT NULL,
    channel           VARCHAR(64)   NOT NULL,
    status            VARCHAR(32)   NOT NULL,
    qr_url            TEXT          NULL,
    qr_ascii          MEDIUMTEXT    NULL,
    last_output       MEDIUMTEXT    NULL,
    remote_pid        BIGINT        NULL,
    restart_status    VARCHAR(32)   NOT NULL DEFAULT '',
    restart_error     TEXT          NULL,
    error_message     TEXT          NULL,
    started_at        DATETIME(3)   NOT NULL,
    expires_at        DATETIME(3)   NOT NULL,
    finished_at       DATETIME(3)   NULL,
    created_at        DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at        DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    UNIQUE KEY uk_channel_login_session_id (session_id),
    KEY idx_channel_login_instance (instance_id, channel, status),
    KEY idx_channel_login_user (user_id, created_at),
    KEY idx_channel_login_expires (status, expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
