package workspaces

import (
	"context"
	"errors"
	"fmt"
)

// Ref is the only durable workspace identity exposed above the driver layer.
// Driver-specific paths, snapshots, containers and epochs are deliberately
// absent from this type.
type Ref struct {
	ID     string `json:"id"`
	Driver string `json:"driver"`
}

func (r Ref) Validate() error {
	if r.ID == "" {
		return errors.New("workspace id is required")
	}
	if r.Driver == "" {
		return errors.New("workspace driver is required")
	}
	return nil
}

func (r Ref) Key() string { return r.Driver + ":" + r.ID }

type Mode string

const (
	ModeReadOnly  Mode = "readOnly"
	ModeReadWrite Mode = "readWrite"
)

type Capabilities struct {
	Fork                bool `json:"fork"`
	PersistentSystem    bool `json:"persistentSystem"`
	PersistentWorkspace bool `json:"persistentWorkspace"`
}

type CreateSpec struct {
	// ID is generated by Manager when omitted. Drivers receive a non-empty ID.
	ID     string
	Driver string
}

type ForkOptions struct {
	// ID is generated by Manager when omitted. Drivers receive a non-empty ID.
	ID string
}

type Principal struct {
	ID       string
	Username string
}

type AttachSpec struct {
	Principal Principal
	Mode      Mode
}

type Endpoint struct {
	Transport string `json:"transport"`
	Host      string `json:"host,omitempty"`
	Port      int    `json:"port,omitempty"`
	Username  string `json:"username,omitempty"`
	Subsystem string `json:"subsystem,omitempty"`
}

type Attachment struct {
	ID        string   `json:"id"`
	Workspace Ref      `json:"workspace"`
	Endpoint  Endpoint `json:"endpoint"`
}

// Driver owns implementation details. In particular SystemView, DataView,
// Btrfs, runc, E2B and remote paths must never leak through this interface.
type Driver interface {
	Name() string
	Capabilities() Capabilities
	Create(context.Context, CreateSpec) (Ref, error)
	Fork(context.Context, Ref, ForkOptions) (Ref, error)
	Attach(context.Context, Ref, AttachSpec) (Attachment, error)
	Detach(context.Context, Attachment) error
	Delete(context.Context, Ref) error
	Exists(context.Context, Ref) (bool, error)
}

var (
	ErrRootWorkspaceDelete = errors.New("root workspace cannot be deleted")
	ErrUnknownDriver       = errors.New("unknown workspace driver")
	ErrRootAlreadyBound    = errors.New("root thread is already bound")
)

func unknownDriver(name string) error {
	return fmt.Errorf("%w: %s", ErrUnknownDriver, name)
}
