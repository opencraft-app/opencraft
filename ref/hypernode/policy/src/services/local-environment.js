import { Service } from "@deepseek-ai/cordis";

export const DEMO_LOCAL_ENVIRONMENT_PATH = "/localhost/polaris/.codex/environments/environment.toml";
export const DEMO_LOCAL_ENVIRONMENT_TOML = `# THIS IS AUTOGENERATED. DO NOT EDIT MANUALLY
version = 1
name = "HyperNode Echo"

[setup]
script = ""

[[actions]]
name = "Echo aaa"
icon = "run"
command = "echo aaa"
`;

function normalizeAbsolutePath(path) {
  if (typeof path !== "string" || !path.startsWith("/")) {
    throw new Error("local environment paths must be absolute");
  }
  const parts = [];
  for (const part of path.split("/")) {
    if (!part || part === ".") continue;
    if (part === "..") parts.pop();
    else parts.push(part);
  }
  return `/${parts.join("/")}`;
}

function dirname(path) {
  const at = path.lastIndexOf("/");
  return at <= 0 ? "/" : path.slice(0, at);
}

function basename(path) {
  return path.slice(path.lastIndexOf("/") + 1);
}

function environmentConfigPath(path) {
  return /\/\.codex\/environments\/[^/]+\.toml$/.test(path);
}

function ownerId(user) {
  return user?.id ?? user?.principalId ?? user?.username ?? "node:root";
}

function bytesFromText(text) {
  if (typeof TextEncoder === "function") return new TextEncoder().encode(text);
  if ((typeof Buffer === "function" || typeof Buffer === "object") && typeof Buffer.from === "function") {
    return Uint8Array.from(Buffer.from(text, "utf8"));
  }
  const bytes = [];
  for (const character of text) {
    const value = character.codePointAt(0);
    if (value <= 0x7f) bytes.push(value);
    else if (value <= 0x7ff) bytes.push(0xc0 | (value >>> 6), 0x80 | (value & 0x3f));
    else if (value <= 0xffff) {
      bytes.push(0xe0 | (value >>> 12), 0x80 | ((value >>> 6) & 0x3f), 0x80 | (value & 0x3f));
    } else {
      bytes.push(
        0xf0 | (value >>> 18),
        0x80 | ((value >>> 12) & 0x3f),
        0x80 | ((value >>> 6) & 0x3f),
        0x80 | (value & 0x3f),
      );
    }
  }
  return Uint8Array.from(bytes);
}

function textFromBytes(bytes) {
  if (typeof TextDecoder === "function") return new TextDecoder().decode(bytes);
  if ((typeof Buffer === "function" || typeof Buffer === "object") && typeof Buffer.from === "function") {
    return Buffer.from(bytes).toString("utf8");
  }
  let result = "";
  for (let index = 0; index < bytes.length;) {
    const first = bytes[index++];
    let value;
    if (first < 0x80) value = first;
    else if ((first & 0xe0) === 0xc0 && index < bytes.length) {
      value = ((first & 0x1f) << 6) | (bytes[index++] & 0x3f);
    } else if ((first & 0xf0) === 0xe0 && index + 1 < bytes.length) {
      value = ((first & 0x0f) << 12) | ((bytes[index++] & 0x3f) << 6) | (bytes[index++] & 0x3f);
    } else if ((first & 0xf8) === 0xf0 && index + 2 < bytes.length) {
      value = ((first & 7) << 18) | ((bytes[index++] & 0x3f) << 12) |
        ((bytes[index++] & 0x3f) << 6) | (bytes[index++] & 0x3f);
    } else value = 0xfffd;
    result += String.fromCodePoint(value);
  }
  return result;
}

function base64FromText(text) {
  if ((typeof Buffer === "function" || typeof Buffer === "object") && typeof Buffer.from === "function") {
    return Buffer.from(text, "utf8").toString("base64");
  }
  let binary = "";
  for (const value of bytesFromText(text)) binary += String.fromCharCode(value);
  return btoa(binary);
}

export class LocalEnvironmentCatalog {
  constructor() {
    this.defaults = new Map();
    this.overrides = new Map();
  }

  normalize(path) {
    return normalizeAbsolutePath(path);
  }

  key(path, user) {
    return `${ownerId(user)}\0${this.normalize(path)}`;
  }

  registerDefault(path, raw) {
    const normalized = this.normalize(path);
    if (!environmentConfigPath(normalized)) throw new Error(`not a local environment config path: ${normalized}`);
    this.defaults.set(normalized, String(raw));
    return normalized;
  }

  write(path, bytes, user = null) {
    const normalized = this.normalize(path);
    if (!environmentConfigPath(normalized)) throw new Error(`not a local environment config path: ${normalized}`);
    this.overrides.set(this.key(normalized, user), textFromBytes(bytes));
    return normalized;
  }

  remove(path, user = null) {
    const normalized = this.normalize(path);
    if (environmentConfigPath(normalized)) return this.overrides.delete(this.key(normalized, user));
    if (!normalized.endsWith("/.codex/environments")) return false;
    let removed = false;
    for (const key of [...this.overrides.keys()]) {
      const configPath = key.slice(key.indexOf("\0") + 1);
      if (dirname(configPath) !== normalized) continue;
      this.overrides.delete(key);
      removed = true;
    }
    return removed;
  }

  raw(path, user = null) {
    const normalized = this.normalize(path);
    return this.overrides.get(this.key(normalized, user)) ?? this.defaults.get(normalized) ?? null;
  }

  configPaths(user = null) {
    const paths = new Set(this.defaults.keys());
    const prefix = `${ownerId(user)}\0`;
    for (const key of this.overrides.keys()) {
      if (key.startsWith(prefix)) paths.add(key.slice(prefix.length));
    }
    return [...paths];
  }

  owns(path, user = null) {
    const normalized = this.normalize(path);
    if (this.raw(normalized, user) != null) return true;
    return this.configPaths(user).some((configPath) => dirname(configPath) === normalized);
  }

  acceptsFile(path) {
    return environmentConfigPath(this.normalize(path));
  }

  acceptsDirectory(path) {
    return this.normalize(path).endsWith("/.codex/environments");
  }

  metadata(path, user = null) {
    const normalized = this.normalize(path);
    const raw = this.raw(normalized, user);
    if (raw != null) {
      return {
        fileName: basename(normalized),
        isDirectory: false,
        isFile: true,
        isSymlink: false,
        createdAtMs: 0,
        modifiedAtMs: 0,
        sizeBytes: bytesFromText(raw).length,
      };
    }
    if (this.configPaths(user).some((configPath) => dirname(configPath) === normalized)) {
      return {
        fileName: basename(normalized),
        isDirectory: true,
        isFile: false,
        isSymlink: false,
        createdAtMs: 0,
        modifiedAtMs: 0,
      };
    }
    return null;
  }

  readDirectory(path, user = null) {
    const normalized = this.normalize(path);
    const entries = this.configPaths(user)
      .filter((configPath) => dirname(configPath) === normalized && this.raw(configPath, user) != null)
      .map((configPath) => ({ fileName: basename(configPath), isDirectory: false, isFile: true }));
    if (entries.length === 0) return null;
    return entries.sort((left, right) => left.fileName.localeCompare(right.fileName));
  }

  readFile(path, user = null) {
    const raw = this.raw(path, user);
    return raw == null ? null : bytesFromText(raw);
  }
}

export class LocalEnvironmentService extends Service {
  constructor(ctx) {
    super(ctx, "localEnvironment");
    this.catalog = new LocalEnvironmentCatalog();
    this.catalog.registerDefault(DEMO_LOCAL_ENVIRONMENT_PATH, DEMO_LOCAL_ENVIRONMENT_TOML);
    ctx.effect(() => ctx.appServer.intercept((message, connection) => this.intercept(message, connection)));
  }

  userFor(connection) {
    if (!connection.identity?.id || !this.ctx.userDirectory) return null;
    return this.ctx.userDirectory.find(connection.identity.id);
  }

  owns(path, user = null) {
    return this.catalog.owns(path, user);
  }

  acceptsFile(path) {
    return this.catalog.acceptsFile(path);
  }

  acceptsDirectory(path) {
    return this.catalog.acceptsDirectory(path);
  }

  normalize(path) {
    return this.catalog.normalize(path);
  }

  metadata(path, user = null) {
    return this.catalog.metadata(path, user);
  }

  readDirectory(path, user = null) {
    return this.catalog.readDirectory(path, user);
  }

  readFile(path, user = null) {
    return this.catalog.readFile(path, user);
  }

  writeFile(params, bytes, user = null) {
    this.catalog.write(params.path, bytes, user);
    return {};
  }

  createDirectory() {
    return {};
  }

  remove(params, user = null) {
    this.catalog.remove(params.path, user);
    return {};
  }

  intercept(message, connection) {
    if (message?.method !== "process/spawn" || message.id === undefined) return false;
    const command = message.params?.command;
    if (!Array.isArray(command) || command.length !== 2 || command[0] !== "cat") return false;
    const user = this.userFor(connection);
    const raw = this.catalog.raw(command[1], user);
    if (raw == null) return false;

    const processHandle = message.params?.processHandle;
    if (typeof processHandle !== "string" || processHandle.length === 0) return false;
    const streamed = message.params?.tty === true || message.params?.streamStdoutStderr === true;
    connection.socket.send({ id: message.id, result: {} });
    this.ctx.appServer.audit(connection, "rpc.response", {
      id: message.id,
      method: message.method,
      resultKeys: [],
      virtualLocalEnvironment: true,
    });
    if (streamed) {
      connection.socket.send({
        method: "process/outputDelta",
        params: {
          processHandle,
          stream: "stdout",
          deltaBase64: base64FromText(raw),
          capReached: false,
        },
      });
    }
    connection.socket.send({
      method: "process/exited",
      params: {
        processHandle,
        exitCode: 0,
        stdout: streamed ? "" : raw,
        stdoutCapReached: false,
        stderr: "",
        stderrCapReached: false,
      },
    });
    console.info(`[local-environment] virtual cat path=${this.catalog.normalize(command[1])} processHandle=${processHandle}`);
    return true;
  }
}

LocalEnvironmentService.inject = ["appServer", "userDirectory"];
