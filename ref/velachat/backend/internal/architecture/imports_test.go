func TestApplicationAndPortsDoNotDependOnOuterLayers(t *testing.T) {
	root := repositoryRoot(t)
	for _, directory := range []string{"internal/app", "internal/ports"} {
		walkGoFiles(t, filepath.Join(root, directory), func(path string, file *ast.File) {
			for _, imported := range file.Imports {
				value, err := strconv.Unquote(imported.Path.Value)
				if err != nil {
					t.Fatalf("%s invalid import: %v", path, err)
				}
				for _, forbidden := range []string{
					"net/http",
					"chatserver/internal/api/openapi",
					"chatserver/internal/ent",
					"github.com/tencent",
					"github.com/redis",
				} {
					if value == forbidden || strings.HasPrefix(value, forbidden+"/") {
						t.Errorf("%s imports forbidden outer dependency %q", path, value)
					}
				}
			}
		})
	}
}

func TestProductionStructuredLogsUseSafeLiteralFields(t *testing.T) {
	root := repositoryRoot(t)
	walkGoFiles(t, filepath.Join(root, "internal"), func(path string, file *ast.File) {
		if strings.HasSuffix(path, "_test.go") ||
			strings.Contains(path, string(filepath.Separator)+"ent"+string(filepath.Separator)) {
			return
		}
		ast.Inspect(file, func(node ast.Node) bool {
			call, ok := node.(*ast.CallExpr)
			if !ok {
				return true
			}
			selector, ok := call.Fun.(*ast.SelectorExpr)
			if !ok || !isLogMethod(selector.Sel.Name) {
				return true
			}
			for _, argument := range call.Args {
				literal, ok := argument.(*ast.BasicLit)
				if !ok || literal.Kind != token.STRING {
					continue
				}
				value, err := strconv.Unquote(literal.Value)
				if err != nil {
					continue
				}
				lower := strings.ToLower(value)
				for _, forbidden := range []string{
					"authorization",
					"password",
					"token",
					"secret",
					"credential",
					"script",
					"websocket",
					"request_body",
					"request_header",
					"request_query",
					"top-secret",
					"should-not-leak",
				} {
					if strings.Contains(lower, forbidden) {
						t.Errorf(
							"%s structured log literal %q contains forbidden marker %q",
							path,
							value,
							forbidden,
						)
					}
				}
			}
			return true
		})
	})
}

func TestGeneratedOpenAPIFileCarriesGeneratorMarker(t *testing.T) {
	root := repositoryRoot(t)
	data, err := fs.ReadFile(
		osDirFS(root),
		"internal/api/openapi/server.gen.go",
	)
	if err != nil {
		t.Fatalf("read generated OpenAPI file: %v", err)
	}
	prefix := string(data)
	if len(prefix) > 512 {
		prefix = prefix[:512]
	}
	if !strings.Contains(prefix, "Code generated by github.com/oapi-codegen/") ||
		!strings.Contains(prefix, "DO NOT EDIT") {
		t.Fatal("server.gen.go is missing generator marker")
	}
}

func walkGoFiles(
	t *testing.T,
	root string,
	visit func(path string, file *ast.File),
) {
	t.Helper()
	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || !strings.HasSuffix(path, ".go") {
			return nil
		}
		parsed, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
		if err != nil {
			return err
		}
		visit(path, parsed)
		return nil
	})
	if err != nil {
		t.Fatalf("walk %s: %v", root, err)
	}
}

func repositoryRoot(t *testing.T) string {
	t.Helper()
	_, currentFile, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("cannot locate architecture test")
	}
	return filepath.Clean(filepath.Join(filepath.Dir(currentFile), "..", ".."))
}

func isLogMethod(name string) bool {
	return name == "Debug" || name == "Info" || name == "Warn" || name == "Error"
}

func osDirFS(root string) fs.FS {
	return os.DirFS(root)
}
